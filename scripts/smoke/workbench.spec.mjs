test('modal dialogs keep keyboard focus inside and restore it on Escape',async({page})=>{
  await page.goto('/')
  const open=page.getByRole('button',{name:'Export',exact:true})
  await open.press('Enter')
  const dialog=page.getByRole('dialog',{name:'Export project',exact:true})
  const close=dialog.getByRole('button',{name:'Close dialog',exact:true})
  const last=dialog.getByRole('button',{name:/Equipment & cable schedule/})
  await expect(close).toBeFocused()
  await expect(page.locator('.workspace-shell')).toHaveAttribute('inert','')
  await page.keyboard.press('Shift+Tab')
  await expect(last).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(open).toBeFocused()
  await expect(page.locator('.workspace-shell')).not.toHaveAttribute('inert','')
})
