  await expect(results.getByText(/Start staged load.*0\.00 V at load.*Tripped/)).toBeVisible()
  await expect(results.getByText(/Remove staged load.*12\.[67]\d V at load/)).toBeVisible()
  await expect(results.getByText(/Isolate the source.*0\.00 V at load/)).toBeVisible()
  await expect(results.getByText(/Restore the source.*12\.[67]\d V at load/)).toBeVisible()
