import {test, expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'

test('solve, probe, wire with the keyboard and round-trip a project',async({page,browser})=>{
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.power-metrics')).toContainText('597 W',{timeout:30000})
  await page.getByRole('button',{name:'Fit system',exact:true}).click()
  await page.getByRole('button',{name:'Voltmeter tool'}).click()
  const battery=page.locator('.react-flow__node').filter({has:page.getByText('Home battery',{exact:true})})
  await battery.locator('[data-handleid="p"]').click()
  await battery.locator('[data-handleid="n"]').click()
  await expect(page.locator('.meter-popover output')).toContainText(/51[.,]\d+ V/)
  await page.getByRole('button',{name:'Voltmeter tool'}).click()
  await page.getByRole('button',{name:'Equipment library',exact:true}).click()
  await page.getByRole('button',{name:'Resistor Linear resistor / discharge load'}).click()
  await page.getByRole('button',{name:'Connect terminals',exact:true}).press('Enter')
  const dialog=page.getByRole('dialog',{name:'Connect terminals'})
  for(const [field,needle] of [['From','Home battery / +'],['To','Resistor / 1']]){
    const select=dialog.getByRole('combobox',{name:field,exact:true})
    const labels=await select.locator('option').allTextContents()
    const index=labels.findIndex(label=>label.includes(needle))
    expect(index).toBeGreaterThan(0)
    await select.press('Home')
    for(let step=0;step<index;step++)await select.press('ArrowDown')
    await expect(select.locator('option:checked')).toHaveText(labels[index])
  }
  await dialog.getByRole('button',{name:'Connect',exact:true}).press('Enter')
  await expect(page.locator('.react-flow__edge')).toHaveCount(12)
  await page.getByRole('button',{name:'Export',exact:true}).click()
  const downloading=page.waitForEvent('download')
  await page.getByRole('button',{name:/Editable project/}).click()
  const data=await readFile(await (await downloading).path())
  const project=JSON.parse(data)
  const clean=await browser.newPage()
  try {
    clean.on('pageerror',error=>errors.push(error.message))
    await clean.goto(page.url())
    await clean.locator('input[type=file]').setInputFiles({name:'round-trip.json',mimeType:'application/json',buffer:data})
    await expect.poll(()=>clean.evaluate(()=>JSON.parse(localStorage.getItem('wisim-workbench-v4'))?.wires)).toEqual(project.wires)
    await expect(clean.locator('.react-flow__node')).toHaveCount(project.devices.length)
    await expect(clean.locator('.power-metrics')).toContainText('597 W',{timeout:30000})
    expect(errors).toEqual([])
  } finally {await clean.close()}
})

test('archive restores the retained versions into a fresh library and previews a collision',async({page,browser})=>{
  await page.goto('/')
  await expect(page.locator('.power-metrics')).toContainText('597 W',{timeout:30000})
  const project=await page.evaluate(()=>JSON.parse(localStorage.getItem('wisim-workbench-v4')))
  await page.getByRole('button',{name:'Save project',exact:true}).click()
  await page.getByRole('link',{name:'WiSim projects',exact:true}).click()
  await page.getByText('Portable project archive',{exact:true}).click()
  await page.getByRole('checkbox',{name:project.name,exact:true}).check()
  const downloading=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download selected projects and versions'}).click()
  const buffer=await readFile(await (await downloading).path())
  const archive=JSON.parse(buffer)
  expect(archive.projects.map(p=>p.id)).toEqual([project.id])
  expect(archive.versions.length).toBeGreaterThan(0)
  const fresh=await browser.newPage()
  try{
    await fresh.goto(page.url())
    await fresh.getByRole('link',{name:'WiSim projects',exact:true}).click()
    await fresh.getByText('Portable project archive',{exact:true}).click()
    const upload=async()=>fresh.getByLabel('Import library archive').setInputFiles({name:'library.json',mimeType:'application/json',buffer})
    await upload()
    await expect(fresh.getByText(/Add to library/)).toBeVisible()
    await fresh.getByRole('button',{name:'Restore archive',exact:true}).click()
    await expect(fresh.getByText('Restore preview',{exact:true})).toHaveCount(0)
    await upload()
    await expect(fresh.getByText(/Restore as a separate copy/)).toBeVisible()
    await fresh.getByRole('button',{name:'Restore archive',exact:true}).click()
    await fresh.getByRole('button',{name:'Previous versions of '+project.name+' (restored copy)',exact:true}).click()
    await expect(fresh.getByRole('button',{name:/Restore saved version/})).toHaveCount(archive.versions.length)
  } finally {await fresh.close()}
})

