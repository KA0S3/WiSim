test('keyboard wiring can cancel and undo without expanding a compact equipment group',async({page})=>{
  await page.goto('/')
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('wisim-workbench-v4')))
  await expect(page.locator('.power-metrics')).toContainText('597 W',{timeout:30000})
  const fixture=await state()
  const inverter=fixture.devices.find(device=>device.kind==='inverter')
  const mppt=fixture.devices.find(device=>device.kind==='mppt')
  fixture.groups=[{id:'compact-cabinet',name:'Compact cabinet',kind:'conversion-stack',members:[inverter.id,mppt.id],collapsed:true,x:inverter.x,y:inverter.y}]
  await page.locator('input[type=file]').setInputFiles({name:'compact.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(fixture))})
  await expect(page.getByText('Compact cabinet',{exact:true}).first()).toBeVisible()
  await page.getByRole('button',{name:'Equipment library',exact:true}).click()
  await page.getByRole('button',{name:'Resistor Linear resistor / discharge load'}).click()
  const launch=page.getByRole('button',{name:'Connect terminals',exact:true})
  const dialog=page.getByRole('dialog',{name:'Connect terminals'})
  await launch.press('Enter')
  await expect(dialog.getByRole('combobox',{name:'From',exact:true})).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(launch).toBeFocused()
  expect((await state()).wires).toEqual(fixture.wires)
  await launch.press('Enter')
  const addedResistor=async()=>(await state()).devices.find(device=>device.kind==='resistor')
  await expect.poll(addedResistor).toBeDefined()
  const resistor=await addedResistor()
  await dialog.getByRole('combobox',{name:'From',exact:true}).selectOption(JSON.stringify([inverter.id,'dc+']))
  await dialog.getByRole('combobox',{name:'To',exact:true}).selectOption(JSON.stringify([resistor.id,'p']))
  await dialog.getByRole('button',{name:'Connect',exact:true}).press('Enter')
  await expect.poll(async()=>(await state()).wires.at(-1)).toMatchObject({from:inverter.id,fromPort:'dc+',to:resistor.id,toPort:'p'})
  expect((await state()).groups[0].collapsed).toBe(true)
  await page.getByRole('button',{name:'Undo',exact:true}).press('Enter')
  await expect.poll(async()=>(await state()).wires).toEqual(fixture.wires)
})

