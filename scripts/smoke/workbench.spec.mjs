  await expect(page.locator('.power-metrics')).toContainText('597 W',{timeout:30000})
  await page.getByRole('button',{name:'Equipment library',exact:true}).click()
  await page.getByRole('button',{name:'Resistor Linear resistor / discharge load'}).click()
  const diagnostics=page.getByRole('button',{name:'System diagnostics',exact:true})
  const note=page.getByRole('article',{name:'info: Unconnected terminal'}).filter({hasText:'Resistor'})
  async function showNotes(){
    await diagnostics.click()
    await page.getByRole('combobox',{name:'Diagnostic severity'}).selectOption('info')
  }
  await showNotes()
  await note.getByText('Explain issue',{exact:true}).click()
  await note.getByText('Add review note',{exact:true}).click()
  await note.getByRole('textbox',{name:'Review note'}).fill('Spare terminal reserved for a later branch.')
